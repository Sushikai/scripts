def search_youtube(keyword: str, count: int = None) -> list[dict]:
    """用yt-dlp ytsearch搜索YouTube视频，支持重试和超时控制"""
    if count is None:
        count = SEARCH_COUNT_PER_KEYWORD
    results = []
    for attempt in range(SEARCH_RETRY):
        try:
            search_query = f"ytsearch{count}:{keyword}"
            cmd = [
                YTDLP_PY, "-m", "yt_dlp",
                "--flat-playlist",
                "--print", "%(id)s|%(duration)s|%(title)s",
                "--no-warnings",
                search_query
            ]
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=SEARCH_TIMEOUT)
            if result.returncode == 0:
                for line in result.stdout.strip().split("\n"):
                    parts = line.split("|", 2)
                    if len(parts) >= 3:
                        vid, dur, title = parts[0].strip(), parts[1].strip(), parts[2].strip()
                        if re.match(r"^[a-zA-Z0-9_-]{10,15}$", vid):
                            try:
                                duration = int(float(dur)) if dur else 0
                            except (ValueError, TypeError):
                                duration = 0
                            results.append({
                                "id": vid,
                                "title": title or f"YouTube {vid}",
                                "keyword": keyword,
                                "duration": duration,
                            })
                log(f"  [搜索] ytsearch '{keyword}' 找到 {len(results)} 个")
                return results
            else:
                err = result.stderr[-300:]
                if attempt < SEARCH_RETRY - 1:
                    log(f"  [搜索] ytsearch '{keyword}' 失败(尝试{attempt+1}/{SEARCH_RETRY}): {err[-100:]}")
                    time.sleep(SEARCH_RETRY_DELAY)
                else:
                    log(f"  [搜索] ytsearch 失败: {err[-200:]}")
        except subprocess.TimeoutExpired:
            if attempt < SEARCH_RETRY - 1:
                log(f"  [搜索] ytsearch '{keyword}' 超时{SEARCH_TIMEOUT}s(尝试{attempt+1}/{SEARCH_RETRY})，重试...")
                time.sleep(SEARCH_RETRY_DELAY)
            else:
                log(f"  [搜索] ytsearch '{keyword}' 超时{SEARCH_TIMEOUT}s * {SEARCH_RETRY}次，退出")
        except Exception as e:
            if attempt < SEARCH_RETRY - 1:
                log(f"  [搜索] ytsearch '{keyword}' 异常(尝试{attempt+1}/{SEARCH_RETRY}): {e}")
                time.sleep(SEARCH_RETRY_DELAY)
            else:
                log(f"  [搜索] ytsearch '{keyword}' 异常: {e}")
    return results


