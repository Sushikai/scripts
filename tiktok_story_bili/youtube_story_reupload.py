def _check_and_fix_audio(video_path: Path) -> bool:
    """检查视频是否有音频轨道，没有则尝试用ffmpeg合并"""
    result = subprocess.run(
        ["ffprobe", "-v", "quiet", "-print_format", "json",
         "-show_streams", str(video_path)],
        capture_output=True, text=True
    )
    if result.returncode == 0 and '"codec_type":"audio"' in result.stdout:
        return True
    log(f"  [音频] 检测到无音频，尝试修复: {video_path.name}")
    # 重新用yt-dlp下载音频+视频合并
    audio_tmp = video_path.with_suffix(".audio.tmp.mp4")
    video_tmp = video_path.with_suffix(".video.tmp.mp4")
    shutil.copy(video_path, video_tmp)
    cmd = [
        YTDLP_PY, "-m", "yt_dlp",
        "--cookies-from-browser", "chrome",
        "--extractor-args", "youtube:player_client=web_safari",
        "--no-playlist",
        "-f", "bestaudio[ext=m4a]/best",
        "--no-warnings",
        "-o", str(audio_tmp),
        f"https://www.youtube.com/watch?v={video_path.stem}"
    ]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=300)
    if r.returncode == 0 and audio_tmp.exists():
        # 用ffmpeg合并
        merge_cmd = [
            "ffmpeg", "-y",
            "-i", str(video_tmp),
            "-i", str(audio_tmp),
            "-c", "copy",
            "-shortest",
            str(video_path)
        ]
        mr = subprocess.run(merge_cmd, capture_output=True, text=True, timeout=120)
        audio_tmp.unlink(missing_ok=True)
        video_tmp.unlink(missing_ok=True)
        if mr.returncode == 0:
            log(f"  [音频] 修复成功: {video_path.name}")
            return True
        video_tmp.unlink(missing_ok=True)
    log(f"  [音频] 修复失败: {video_path.name}")
    audio_tmp.unlink(missing_ok=True)
    video_tmp.unlink(missing_ok=True)
    return False

