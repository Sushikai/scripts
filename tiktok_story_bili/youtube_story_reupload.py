def generate_cover(video_file: Path, vid: str, title: str) -> Path:
    """从视频提取关键帧作为封面，加标题文字"""
    cover_path = WORK_DIR / f"{vid}_cover.png"
    if cover_path.exists():
        return cover_path

    thumb = WORK_DIR / f"{vid}_thumb.jpg"

    # 1. 尝试提取视频第一帧
    try:
        r = subprocess.run([
            "ffmpeg", "-y", "-i", str(video_file),
            "-vf", "select=eq(n\,0),scale=1280:720",
            "-frames:v", "1", "-q:v", "2",
            str(thumb)
        ], capture_output=True, text=True, timeout=60)
        if r.returncode != 0 or not thumb.exists():
            raise ValueError("ffmpeg frame grab failed")
    except Exception:
        # fallback：纯色封面
        from PIL import Image, ImageDraw, ImageFont
        img = Image.new('RGB', (1280, 720), color=(20, 25, 60))
        draw = ImageDraw.Draw(img)
        words = "AI Story"
        try:
            font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", 60)
        except Exception:
            font = ImageFont.load_default()
        bbox = font.getbbox(words)
        bw, bh = bbox[2] - bbox[0], bbox[3] - bbox[1]
        draw.text(((1280-bw)//2, (720-bh)//2), words, fill=(200, 200, 255), font=font)
        img.save(cover_path)
        return cover_path

    # 2. PIL处理：缩放+加文字遮罩
    try:
        from PIL import Image as PILImage, ImageDraw, ImageFont
        img = PILImage.open(thumb).convert("RGB")
        img = img.resize((1280, 720), PILImage.LANCZOS)
        draw = ImageDraw.Draw(img)
        # 半透明黑色底部遮罩
        overlay = PILImage.new('RGB', (1280, 720), (0, 0, 0))
        mask = PILImage.new('L', (1280, 720), 0)
        mask_draw = ImageDraw.Draw(mask)
        mask_draw.rectangle([(0, 560), (1280, 720)], fill=180)
        overlay.paste(img, (0, 0))
        img = PILImage.composite(overlay, PILImage.new('RGB', (1280, 720), (0, 0, 0)), mask)
        draw = ImageDraw.Draw(img)
        short_title = title[:30] + ("…" if len(title) > 30 else "")
        try:
            font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial.ttf", 48)
        except Exception:
            font = ImageFont.load_default()
        draw.text((40, 570), short_title, fill=(255, 255, 255), font=font)
        draw.text((40, 640), "AI故事视频", fill=(180, 180, 255), font=font)
        img.save(cover_path, quality=92)
        thumb.unlink(missing_ok=True)
    except Exception as e:
        log(f"  [封面] PIL处理失败: {e}")
        if thumb.exists() and not cover_path.exists():
            thumb.rename(cover_path)

    return cover_path


