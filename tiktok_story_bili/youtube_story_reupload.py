def generate_search_keywords() -> list[str]:
    """用LLM根据当前热点生成AI视频搜索关键词，返回5个不重复的英文关键词"""
    try:
        from llm_utils import call_ollama

        prompt = """You are a TikTok content trends analyst specializing in AI-generated videos.

Current date: 2026-05-30

Generate exactly 5 diverse English search keywords for finding viral AI-generated story/narrative videos on TikTok.

Requirements:
1. Mix of video styles: short films, emotional stories, sci-fi, fantasy, horror, romance, comedy, drama
2. Each keyword must be distinct and NOT overlap with others
3. Use terms like: AI generated, AI story, AI narrative, artificial intelligence, machine story, etc.
4. Focus on content that has high viral potential (emotional, surprising, dramatic)
5. Keywords should be 3-7 words each

Output format (just the keywords, one per line, no numbers or bullets:
[keyword1]
[keyword2]
[keyword3]
[keyword4]
[keyword5]"""

        result = call_ollama(prompt, system="You are a TikTok content analyst. Output only the keywords, one per line, no numbers or bullets.")
        if not result:
            raise ValueError("Empty result")
        text = result.strip()
        import re as re_module
        raw_lines = text.split("\n")
        keywords = []
        for line in raw_lines:
            line = line.strip()
            if not line or len(line) < 4:
                continue
            skip_words = ['i need', 'each ', 'focus on', 'keywords should', 'output format', 'your task', 'generate exactly', 'must be', 'use terms', 'mix of']
            lower_line = line.lower()
            if any(sw in lower_line for sw in skip_words):
                continue
            quoted = re_module.findall(r'"([^"]+)"', line)
            if quoted:
                keywords.extend(quoted)
            else:
                cleaned = re_module.sub(r'^[\-\*\d\.\)\s]+', '', line).strip()
                cleaned = re_module.sub(r'\s*[-–]\s*covers?\s*.*$', '', cleaned).strip()
                if len(cleaned.split()) >= 2 and len(cleaned.split()) <= 7:
                    keywords.append(cleaned)

        seen = set()
        unique_keywords = []
        for k in keywords:
            k_lower = k.lower()
            if k_lower not in seen and len(k) > 3:
                seen.add(k_lower)
                unique_keywords.append(k)

        if len(unique_keywords) >= 3:
            log(f"[LLM] 生成关键词: {unique_keywords[:5]}")
            return unique_keywords[:5]
    except Exception as e:
        log(f"[LLM] 关键词生成失败: {e}")

    return [
        "AI story short film emotional",
        "AI generated narrative drama",
        "artificial intelligence fiction",
        "AI cinematic story viral",
        "machine learning short movie",
    ]

