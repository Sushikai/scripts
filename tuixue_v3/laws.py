def flat_laws() -> list[dict]:
    """展平全部条目 → [{cat_num, cat_name, idx, text}, ...]"""
    out: list[dict] = []
    for c in CATEGORIES:
        for i, t in enumerate(c["items"], 1):
            out.append({
                "cat_num": c["num"],
                "cat_name": c["name"],
                "idx": f"{c['num']}.{i}",
                "text": t,
            })
    return out


def as_prompt() -> str:
    """给 LLM 的格式化文本（AI 复盘使用）"""
    lines: list[str] = []
    for c in CATEGORIES:
        lines.append(f"【{c['num']}·{c['name']}】{c['sub']}")
        for i, t in enumerate(c["items"], 1):
            lines.append(f"  {c['num']}.{i} {t}")
    return "\n".join(lines)


