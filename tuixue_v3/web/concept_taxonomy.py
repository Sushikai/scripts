CONCEPT_TO_L3: dict[str, tuple[str, str]] = {}  # kw -> (l3, l4_label)
for _kw, _l3, _lbl in CONCEPT_L4:
    CONCEPT_TO_L3[_kw] = (_l3, _lbl)

L3_TO_CLUSTER: dict[str, str] = {l3: info["cluster"] for l3, info in CONCEPT_L3.items()}


def match_concepts(text: str | None) -> list[tuple[str, list[str]]]:
    """从文本(主营/概念/名称)里匹配,返回 [(l3_chain, [l4_label...]), ...]。
    按命中顺序,同一 L3 只返一次(合并 L4)。
    """
    if not text:
        return []
    s = str(text)
    seen_l3: dict[str, list[str]] = {}
    # 优先匹配长 keyword(避免 GPU 抢 CPU)
    sorted_kws = sorted(CONCEPT_TO_L3.keys(), key=lambda x: -len(x))
    for kw in sorted_kws:
        if kw in s:
            l3, l4_label = CONCEPT_TO_L3[kw]
            seen_l3.setdefault(l3, [])
            if l4_label and l4_label not in seen_l3[l3]:
                seen_l3[l3].append(l4_label)
    return [(l3, l4s) for l3, l4s in seen_l3.items()]


def concept_signature(text: str | None) -> dict:
    """返回包含的 (cluster -> [l3, ...]) 签名。"""
    matched = match_concepts(text)
    cluster: dict[str, list[str]] = {}
    for l3, l4s in matched:
        cl = L3_TO_CLUSTER.get(l3, "其他")
        cluster.setdefault(cl, [])
        if l3 not in cluster[cl]:
            cluster[cl].append(l3)
    return {
        "matched": [{"l3": l3, "l4": l4s, "cluster": L3_TO_CLUSTER.get(l3, "其他")} for l3, l4s in matched],
        "by_cluster": cluster,
        "primary_cluster": max(cluster.keys(), key=lambda k: len(cluster[k])) if cluster else "",
    }


